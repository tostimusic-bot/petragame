create table if not exists public.petra_submissions (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 40),
  answers jsonb not null,
  score integer not null check (score between 0 and 10),
  created_at timestamptz not null default now()
);

alter table public.petra_submissions enable row level security;

-- Cualquiera puede enviar su participación (sin leer resultados).
create policy "public can submit" on public.petra_submissions
for insert to anon, authenticated
with check (
  char_length(player_name) between 1 and 40
  and jsonb_typeof(answers) = 'array'
  and jsonb_array_length(answers) = 10
  and score between 0 and 10
);

-- Solo usuarios autenticados (Laura, cuyo usuario crearás manualmente) pueden consultar resultados.
create policy "admins can read results" on public.petra_submissions
for select to authenticated
using (true);
