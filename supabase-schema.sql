-- PETRA · Base de datos para 23 curiosidades
-- En Supabase: SQL Editor > New query > pega todo > Run.

create table if not exists public.petra_submissions (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 40),
  answers jsonb not null,
  score integer not null check (score between 0 and 23),
  created_at timestamptz not null default now()
);

-- Si ya habías creado la tabla de la demo anterior, amplía el rango de puntuación.
alter table public.petra_submissions
  drop constraint if exists petra_submissions_score_check;
alter table public.petra_submissions
  add constraint petra_submissions_score_check check (score between 0 and 23);

alter table public.petra_submissions enable row level security;

-- Elimina políticas anteriores con estos nombres para poder ejecutar el script de nuevo.
drop policy if exists "public can submit" on public.petra_submissions;
drop policy if exists "admins can read results" on public.petra_submissions;

-- Los jugadores pueden enviar, pero no leer, respuestas.
create policy "public can submit" on public.petra_submissions
for insert to anon, authenticated
with check (
  char_length(player_name) between 1 and 40
  and jsonb_typeof(answers) = 'array'
  and jsonb_array_length(answers) = 23
  and score between 0 and 23
);

-- Solo usuarios autenticados (Laura) pueden consultar las participaciones.
create policy "admins can read results" on public.petra_submissions
for select to authenticated
using (true);
